/*
 * CTF flag integrity
 * ------------------
 * app/flags.properties is the plaintext source of truth for maintainers. It is never packaged:
 * generate<Variant>FlagVault turns it into FlagVaultData.java (XOR-encoded bytes + SHA-256
 * digests), so `strings classes.dex | grep EVILCORP{` finds nothing. verifyNoPlaintextFlags
 * fails the build if a flag ever leaks into the debug APK as plaintext again.
 */
abstract class GenerateFlagVaultTask : DefaultTask() {
    @get:InputFile
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val flagsFile: RegularFileProperty

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun generate() {
        val source = flagsFile.get().asFile
        val props = Properties().apply { source.inputStream().use(::load) }
        val ids = props.stringPropertyNames().sorted()
        require(ids.isNotEmpty()) { "No flags defined in $source" }
        val format = Regex("EVILCORP\\{[A-Za-z0-9_]+}")
        ids.forEach { id ->
            require(id.matches(Regex("[a-z]+"))) { "Invalid lab id '$id' in $source" }
            require(props.getProperty(id).matches(format)) { "Flag for '$id' must match $format" }
        }
        val plain = ids.map { props.getProperty(it).toByteArray(Charsets.UTF_8) }
        require(plain.map { String(it) }.toSet().size == plain.size) { "Flags in $source must be unique" }

        // Must stay in sync with seed()/key() in the generated Java below.
        fun seed(id: String): Int = id.fold(0x45C0) { s, c -> (s * 31 + c.code) and 0x7fffffff }
        fun key(seed: Int, i: Int): Int = ((seed ushr ((i and 3) * 8)) + i * 0x5B + 0x21) and 0xFF
        fun literal(bytes: ByteArray) =
            bytes.joinToString(", ", prefix = "        { ", postfix = " },") { "(byte) 0x%02x".format(it.toInt() and 0xFF) }

        val encoded = ids.mapIndexed { idx, id ->
            val s = seed(id)
            ByteArray(plain[idx].size) { i -> (plain[idx][i].toInt() xor key(s, i)).toByte() }
        }
        val digests = plain.map { MessageDigest.getInstance("SHA-256").digest(it) }

        val java = buildString {
            appendLine("// Generated by :app:generate<Variant>FlagVault from app/flags.properties. Do not edit.")
            appendLine("package com.evilcorp.android.labs;")
            appendLine()
            appendLine("import java.nio.charset.StandardCharsets;")
            appendLine()
            appendLine("/** XOR-encoded lab flags and their SHA-256 digests. See FlagVault. */")
            appendLine("final class FlagVaultData {")
            appendLine("    private FlagVaultData() {}")
            appendLine()
            appendLine("    static final String[] IDS = {")
            ids.forEach { appendLine("        \"$it\",") }
            appendLine("    };")
            appendLine()
            appendLine("    private static final byte[][] ENCODED = {")
            encoded.forEach { appendLine(literal(it)) }
            appendLine("    };")
            appendLine()
            appendLine("    private static final byte[][] DIGESTS = {")
            digests.forEach { appendLine(literal(it)) }
            appendLine("    };")
            appendLine()
            appendLine("    static int indexOf(String id) {")
            appendLine("        for (int i = 0; i < IDS.length; i++) {")
            appendLine("            if (IDS[i].equals(id)) return i;")
            appendLine("        }")
            appendLine("        return -1;")
            appendLine("    }")
            appendLine()
            appendLine("    static String reveal(String id) {")
            appendLine("        int index = indexOf(id);")
            appendLine("        if (index < 0) return null;")
            appendLine("        byte[] enc = ENCODED[index];")
            appendLine("        byte[] out = new byte[enc.length];")
            appendLine("        int seed = seed(id);")
            appendLine("        for (int i = 0; i < enc.length; i++) {")
            appendLine("            out[i] = (byte) (enc[i] ^ key(seed, i));")
            appendLine("        }")
            appendLine("        return new String(out, StandardCharsets.UTF_8);")
            appendLine("    }")
            appendLine()
            appendLine("    static byte[] digest(String id) {")
            appendLine("        int index = indexOf(id);")
            appendLine("        return index < 0 ? null : DIGESTS[index].clone();")
            appendLine("    }")
            appendLine()
            appendLine("    private static int seed(String id) {")
            appendLine("        int s = 0x45C0;")
            appendLine("        for (int i = 0; i < id.length(); i++) {")
            appendLine("            s = (s * 31 + id.charAt(i)) & 0x7fffffff;")
            appendLine("        }")
            appendLine("        return s;")
            appendLine("    }")
            appendLine()
            appendLine("    private static int key(int seed, int i) {")
            appendLine("        return ((seed >>> ((i & 3) * 8)) + i * 0x5B + 0x21) & 0xFF;")
            appendLine("    }")
            appendLine("}")
        }

        val out = outputDir.get().asFile.resolve("com/evilcorp/android/labs/FlagVaultData.java")
        out.parentFile.mkdirs()
        out.writeText(java)
    }
}

abstract class VerifyNoPlaintextFlagsTask : DefaultTask() {
    @get:InputDirectory
    @get:PathSensitive(PathSensitivity.NONE)
    abstract val apkDirectory: DirectoryProperty

    @TaskAction
    fun verify() {
        val pattern = Regex("EVILCORP\\{[A-Za-z0-9_]+}")
        val apks = apkDirectory.get().asFile.walkTopDown().filter { it.isFile && it.extension == "apk" }.toList()
        if (apks.isEmpty()) throw GradleException("No APK found in ${apkDirectory.get().asFile}")
        val hits = mutableListOf<String>()
        apks.forEach { apk ->
            ZipFile(apk).use { zip ->
                zip.entries().asSequence().filterNot { it.isDirectory }.forEach { entry ->
                    val text = zip.getInputStream(entry).use { it.readBytes() }.toString(Charsets.ISO_8859_1)
                    pattern.findAll(text).forEach { hits += "${apk.name}!/${entry.name}: ${it.value}" }
                }
            }
        }
        if (hits.isNotEmpty()) {
            throw GradleException("Plaintext CTF flags found in the APK:\n" + hits.joinToString("\n"))
        }
        logger.lifecycle("verifyNoPlaintextFlags: no plaintext flags in ${apks.joinToString { it.name }}")
    }
}

androidComponents {
    onVariants { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        val generate = tasks.register<GenerateFlagVaultTask>("generate${name}FlagVault") {
            flagsFile.set(layout.projectDirectory.file("flags.properties"))
        }
        variant.sources.java?.addGeneratedSourceDirectory(generate, GenerateFlagVaultTask::outputDir)
    }
    onVariants(selector().withBuildType("debug")) { variant ->
        val name = variant.name.replaceFirstChar { it.uppercase() }
        tasks.register<VerifyNoPlaintextFlagsTask>("verify${name}NoPlaintextFlags") {
            apkDirectory.set(variant.artifacts.get(SingleArtifact.APK))
        }
    }
}

tasks.register("verifyNoPlaintextFlags") {
    group = "verification"
    description = "Fails if any EVILCORP{...} flag is stored as plaintext in the debug APK."
    dependsOn("verifyDebugNoPlaintextFlags")
}
